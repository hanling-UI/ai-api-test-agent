def _fix(run, size=None, bold=None, color=None):
    run.font.name = FONT
    run.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    if size:
        run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)


def h(text, level=1):
    p = doc.add_heading(text, level=level)
    for r in p.runs:
        _fix(r)
    return p


def p(text, size=10.5, bold=False, color=None, style=None):
    par = doc.add_paragraph(style=style) if style else doc.add_paragraph()
    _fix(par.add_run(text), size, bold, color)
    return par


def b(text, prefix=None):
    par = doc.add_paragraph(style="List Bullet")
    if prefix:
        _fix(par.add_run(prefix), 10.5, True)
    _fix(par.add_run(text))
    return par


def qa_block(questions):
    """questions: [(问, 答)]"""
    for i, (q, a) in enumerate(questions, 1):
        par = doc.add_paragraph()
        _fix(par.add_run(f"Q{i}. {q}"), 10.5, True)
        par2 = doc.add_paragraph()
        _fix(par2.add_run(f"A：{a}"), 10)


def table(headers, rows, font_size=9, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, htext in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        _fix(cell.paragraphs[0].add_run(htext), font_size, True)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            _fix(cells[i].paragraphs[0].add_run(str(val)), font_size)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = w
    doc.add_paragraph()
    return t


